const STRINGS = { en, it };
export let LANG = "en";

export function t(key, vars) {
  let s = (STRINGS[LANG] && STRINGS[LANG][key]) || en[key];
  if (s == null) return key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split("{" + k + "}").join(v);
  return s;
}
export const has = (key) => en[key] != null;
export const units = () => ({ s: t("u_s"), min: t("u_min"), h: t("u_h") });

/** "auto" follows the browser; the page's static labels are filled from data-i18n* attributes. */
export function applyLanguage(setting) {
  const browser = (navigator.language || "en").toLowerCase().startsWith("it") ? "it" : "en";
  LANG = setting === "en" || setting === "it" ? setting : browser;
  document.documentElement.lang = LANG;
  setLocale(LANG);
  document.querySelectorAll("[data-i18n]").forEach((e) => { e.textContent = t(e.dataset.i18n); });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((e) => { e.placeholder = t(e.dataset.i18nPlaceholder); });
  document.querySelectorAll("[data-i18n-aria]").forEach((e) => { e.setAttribute("aria-label", t(e.dataset.i18nAria)); });
  document.querySelectorAll("[data-i18n-title]").forEach((e) => { e.title = t(e.dataset.i18nTitle); });
}
