"""Tune the engine to this machine: measure the settings that do not change the output, keep what is faster.

Policy: only lossless settings are ever tried (catalog.LOSSLESS_SETTINGS). The speed switches that change the
numbers (catalog.LOSSY_ENV) are never set.

The benchmark is short and fixed: the same prompts every time, temperature 0, thinking off, and the server's own
timings (prefill and decode rates from `timings`), so two runs on one machine are comparable.

Method (A ... A): the defaults are measured first and again at the end. The better of the two is the reference,
and their difference is the noise of this machine during this run: a first measurement on a cold machine is
slower, and would make every later setting look like a gain. Between the two, each candidate is the defaults plus
one setting, measured after one discarded warm-up request on a fresh engine start. A setting is kept only if its
target number beats the reference by more than GAIN and by more than the noise, without making another one worse
by more than SLACK (or the noise). When more than one setting is kept they are measured once more together, and
the combination is used only if it holds up; otherwise the single best one is. The result is this machine's
profile (tuning.json), which the engine's launch uses until it is reverted.
"""

import json
import re
import threading
import time
import urllib.error
import urllib.request
from pathlib import Path
from typing import Any, Callable, Dict, List, Optional

from . import catalog, machine
from .engine import Engine, EngineError, clean_profile
from .store import write_json_atomic

BENCH = "capy-bench 2"  # 2: a warm-up before every measurement, the defaults measured twice (A ... A)
GAIN = 0.03
SLACK = 0.03
STEP_GAIN = 0.01  # keep walking the thread count while each step still gains this much
WARMUP_TOKENS = 64  # generated by the discarded warm-up request, after a prompt as long as the measured one
DECODE_TOKENS = 384
PREFILL_WORDS = 4500  # about 6k tokens
SHORT_WORDS = 300  # about 400 tokens: around the --stream-min-tokens threshold
LONG_WORDS = 18000  # about 24k tokens
BENCH_SECONDS = 18.0  # estimates, replaced by what is measured as the run goes
LONG_SECONDS = 20.0
CALIBRATE_SECONDS = 75.0  # --miss-split calibrate fits its costs on the first 4,096 decode calls
DEFAULT_LOAD = {"flash-next": 90.0, "27b": 30.0}
LOWER_IS_BETTER = ("short_ms",)

DECODE_PROMPTS = (
    "Explain step by step, in plain words, how the cache hierarchy of a CPU (L1, L2, L3) makes a program faster. "
    "Write at least six paragraphs.",
    "Write a Python module with an LRU cache class (get, put, a size limit), a docstring and a comment for every "
    "method, then explain the complexity of each operation.",
)
_WORDS = (
    "river stone copper window ledger harbor signal meadow engine lantern border garden silver thread market "
    "winter bridge paper anchor valley marble orchard station pocket mirror candle forest letter island "
    "hammer saddle velvet morning kernel packet buffer vector tensor memory socket branch commit schema "
    "column record cursor latency budget margin report figure sample result method"
).split()


def filler(words: int, seed: int = 7) -> str:
    """The same pseudo-text everywhere (a fixed generator, no randomness): sentences of ordinary words."""
    out, state = [], seed
    for i in range(words):
        state = (state * 1103515245 + 12345) % 2147483648
        word = _WORDS[state % len(_WORDS)]
        out.append(word.capitalize() if i % 11 == 0 else word)
        if i % 11 == 10:
            out[-1] += "."
    return " ".join(out)


class BenchError(Exception):
    pass


class Cancelled(Exception):
    pass


def _post(url: str, body: Dict[str, Any], timeout: float) -> Dict[str, Any]:
    request = urllib.request.Request(
        url, data=json.dumps(body).encode("utf-8"), headers={"Content-Type": "application/json"}
    )
    try:
        with urllib.request.urlopen(request, timeout=timeout) as r:
            return json.loads(r.read().decode("utf-8"))
    except urllib.error.HTTPError as e:
        raise BenchError(f"the engine answered HTTP {e.code} to a benchmark request")
    except (OSError, ValueError) as e:
        raise BenchError(f"the engine did not answer a benchmark request: {getattr(e, 'reason', e)}")


def ask(base_url: str, model_id: str, prompt: str, max_tokens: int, timeout: float = 600.0) -> Dict[str, float]:
    """One request; returns the server's timings (llama.cpp-compatible `timings`)."""
    reply = _post(
        base_url + "/chat/completions",
        {
            "model": model_id,
            "messages": [{"role": "user", "content": prompt}],
            "max_tokens": max_tokens,
            "temperature": 0,
            "stream": False,
            "chat_template_kwargs": {"enable_thinking": False},
        },
        timeout,
    )
    timings = reply.get("timings")
    if not isinstance(timings, dict) or "predicted_per_second" not in timings:
        raise BenchError("the engine did not report timings for a benchmark request")
    return {k: float(v) for k, v in timings.items() if isinstance(v, (int, float))}


def _median(values: List[float]) -> float:
    ordered = sorted(values)
    mid = len(ordered) // 2
    return ordered[mid] if len(ordered) % 2 else (ordered[mid - 1] + ordered[mid]) / 2


def measure(
    base_url: str,
    model_id: str,
    long_context: bool = False,
    cancel: Optional[threading.Event] = None,
    nonce: Optional[str] = None,
) -> Dict[str, float]:
    """The benchmark: decode rate, prefill rate on a fresh ~6k-token prompt, time to the first token of a fresh
    ~400-token prompt; with `long_context` also prefill and decode on ~24k tokens."""
    nonce = nonce or "%x" % int(time.time() * 1000)

    def check() -> None:
        if cancel is not None and cancel.is_set():
            raise Cancelled()

    def fresh(words: int, tag: str, max_tokens: int = 8) -> Dict[str, float]:
        # A different first line every run: the prefix cache cannot answer for the prefill.
        prompt = f"[run {nonce}-{tag}] Read these notes, then reply with the single word OK.\n\n" + filler(
            words, seed=7 + len(tag)
        )
        return ask(base_url, model_id, prompt, max_tokens)

    out: Dict[str, float] = {}
    decode = []
    for n, prompt in enumerate(DECODE_PROMPTS):
        check()
        decode.append(ask(base_url, model_id, f"[run {nonce}-d{n}] {prompt}", DECODE_TOKENS)["predicted_per_second"])
    out["decode_tps"] = round(_median(decode), 1)
    check()
    out["prefill_tps"] = round(fresh(PREFILL_WORDS, "p")["prompt_per_second"], 1)
    check()
    out["short_ms"] = round(fresh(SHORT_WORDS, "s").get("prompt_ms", 0.0), 1)
    if long_context:
        check()
        timings = fresh(LONG_WORDS, "long", max_tokens=256)
        out["long_prefill_tps"] = round(timings["prompt_per_second"], 1)
        out["long_decode_tps"] = round(timings["predicted_per_second"], 1)
    return out


def gain(new: Dict[str, float], old: Dict[str, float], metric: str) -> float:
    """Relative improvement of `metric` (positive is better, whichever way the metric goes)."""
    a, b = new.get(metric), old.get(metric)
    if not a or not b:
        return 0.0
    return (b - a) / b if metric in LOWER_IS_BETTER else (a - b) / b


def worth_it(
    new: Dict[str, float], old: Dict[str, float], target: str, noise: Optional[Dict[str, float]] = None
) -> bool:
    """Better than the reference on its target by GAIN and by more than the noise, and nothing else worse by more
    than SLACK (or than the noise, where the machine itself varies more than that)."""
    noise = noise or {}
    improvement = gain(new, old, target)
    if improvement < GAIN or improvement <= noise.get(target, 0.0):
        return False
    return all(gain(new, old, m) >= -max(SLACK, noise.get(m, 0.0)) for m in old if m != target and m in new)


def reference_and_noise(first: Dict[str, float], second: Dict[str, float]):
    """From two measurements of the same defaults (A ... A): the better value of each number, and how far apart the
    two were, as a fraction of the better one."""
    reference: Dict[str, float] = {}
    noise: Dict[str, float] = {}
    for metric, a in first.items():
        b = second.get(metric)
        if not b or not a:
            reference[metric] = a or b or 0.0
            continue
        best = min(a, b) if metric in LOWER_IS_BETTER else max(a, b)
        reference[metric] = best
        noise[metric] = round(abs(a - b) / best, 4)
    return reference, noise


def signature(facts: Dict[str, Any]) -> Dict[str, Any]:
    """What a profile was measured on: a profile from other hardware is not applied."""
    return {
        "cpu": facts["cpu"]["model"],
        "cores": facts["cpu"]["physical_cores"],
        "gpus": [g["name"] for g in facts["gpus"] if g["usable"]],
    }


class ProfileStore:
    """tuning.json: per model, the flags chosen for this machine, the numbers before and after, every trial."""

    def __init__(self, path: Path):
        self.path = Path(path)
        self._lock = threading.Lock()

    def _load(self) -> Dict[str, Any]:
        try:
            with open(self.path, encoding="utf-8") as f:
                value = json.load(f)
            if isinstance(value, dict):
                value.setdefault("profiles", {})
                value.setdefault("load_seconds", {})
                return value
        except (OSError, ValueError):
            pass
        return {"version": 1, "profiles": {}, "load_seconds": {}}

    def record(self, key: str) -> Optional[Dict[str, Any]]:
        value = self._load()["profiles"].get(key)
        return value if isinstance(value, dict) else None

    def flags(self, key: str, facts: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
        """The flags the launch should use: the active profile, if it was measured on this hardware."""
        record = self.record(key)
        model = catalog.model(key)
        if not record or not model or not record.get("active"):
            return {}
        if facts is not None and record.get("machine") != signature(facts):
            return {}
        return clean_profile(model, record.get("flags"))

    def save(self, key: str, record: Dict[str, Any]) -> None:
        with self._lock:
            value = self._load()
            value["profiles"][key] = record
            write_json_atomic(self.path, value)

    def set_active(self, key: str, active: bool) -> bool:
        with self._lock:
            value = self._load()
            record = value["profiles"].get(key)
            if not isinstance(record, dict):
                return False
            record["active"] = bool(active)
            write_json_atomic(self.path, value)
            return True

    def load_seconds(self, key: str) -> Optional[float]:
        value = self._load()["load_seconds"].get(key)
        return float(value) if isinstance(value, (int, float)) else None

    def note_load(self, key: str, seconds: float) -> None:
        with self._lock:
            value = self._load()
            value["load_seconds"][key] = round(seconds, 1)
            write_json_atomic(self.path, value)


def steps_for(model: Dict[str, Any], facts: Dict[str, Any], long_context: bool) -> List[Dict[str, Any]]:
    """What is worth trying for this model on this machine, with the most engine starts each step can take."""
    steps: List[Dict[str, Any]] = []
    for s in catalog.LOSSLESS_SETTINGS:
        if not catalog.applies(s, model):
            continue
        if s["key"] == "gpus" and not (len(model["gpus"]) > 1 and facts["usable_gpus"] >= 2):
            continue
        if s["metric"].startswith("long_") and not long_context:
            continue
        steps.append({"id": s["id"], "runs": s["runs"]})
    return steps


class Tuner:
    def __init__(
        self, engine: Engine, machine_: machine.Machine, profiles: ProfileStore, version: Callable[[], str] = lambda: ""
    ):
        self.engine = engine
        self.machine = machine_
        self.profiles = profiles
        self._version = version
        self._cancel = threading.Event()
        self._thread: Optional[threading.Thread] = None
        self._lock = threading.Lock()
        self.state = "idle"  # idle | running | done | failed | cancelled
        self.model: Optional[str] = None
        self.long_context = False
        self.step = ""
        self.label = ""
        self.done = 0
        self.total = 0
        self.started: Optional[float] = None
        self.finished: Optional[float] = None
        self.trials: List[Dict[str, Any]] = []
        self.baseline: Optional[Dict[str, float]] = None
        self.best: Optional[Dict[str, float]] = None
        self.flags: Dict[str, Any] = {}
        self.noise: Dict[str, float] = {}  # per number: how far apart the two runs of the defaults were
        self.baselines: List[Dict[str, float]] = []
        self.error: Optional[str] = None
        self._per_run: List[float] = []
        self._running_profile: Optional[Dict[str, Any]] = None
        self._restore_engine = True

    # ---- before it runs -----------------------------------------------------------------------------------------
    def plan(self, key: str, long_context: bool = False) -> Dict[str, Any]:
        """The steps and an honest estimate of the time: engine starts x (load time + benchmark)."""
        model = catalog.model(key)
        if model is None:
            raise ValueError("unknown model: " + str(key))
        facts = self.machine.facts()
        steps = steps_for(model, facts, long_context)
        load = self.profiles.load_seconds(key) or self.engine.load_seconds or DEFAULT_LOAD[model["family"]]
        candidates = sum(s["runs"] for s in steps)
        running_default = self.engine.state == "running" and self.engine.model == key and not self.engine.profile
        # Engine starts: one per candidate, back to the defaults for the second baseline, and the last one with the
        # result (the kept settings together); plus the first if the engine is not already running the defaults.
        starts = (candidates + 2 if steps else 0) + (0 if running_default else 1)
        measurements = candidates + (3 if steps else 2)
        seconds = starts * load + measurements * BENCH_SECONDS
        if any(s["id"] == "miss_split" for s in steps):
            seconds += CALIBRATE_SECONDS
        long_runs = 4 if any(s["id"] == "kv_ram" for s in steps) else 0  # both baselines, the candidate, the result
        seconds += long_runs * LONG_SECONDS
        return {
            "model": key,
            "steps": steps,
            "measurements": measurements,
            "seconds": round(seconds),
            "load_seconds": load,
            "tunable": bool(steps),
            "long_context": bool(long_context),
            # what the long-context test adds: one more candidate, and a long prompt in four measurements
            "long_extra_seconds": round(load + BENCH_SECONDS + 4 * LONG_SECONDS) if steps else 0,
        }

    # ---- run ------------------------------------------------------------------------------------------------------
    def start(self, key: str, long_context: bool = False) -> Dict[str, Any]:
        plan = self.plan(key, long_context)
        with self._lock:
            if self.state == "running":
                raise EngineError("busy", "a tuning run is already in progress")
            if self.engine.state not in ("running", "starting"):
                self.engine.check(key, {})  # say now why the engine cannot start, not after the first minute
            self._cancel = threading.Event()
            self._restore_engine = True
            self._plan = plan
            self.state, self.model, self.long_context = "running", key, bool(long_context)
            self.step, self.label, self.done, self.total = "baseline", "", 0, plan["measurements"]
            self.started, self.finished, self.trials, self.error = time.time(), None, [], None
            self.baseline, self.best, self.flags, self._per_run = None, None, {}, []
            self.noise, self.baselines = {}, []
            self._running_profile = None
            self._thread = threading.Thread(target=self._run, args=(key, plan), daemon=True, name="capy-tune")
            self._thread.start()
        return plan

    def cancel(self, restore: bool = True) -> bool:
        """Stop the run. `restore`: start the engine again as it ran before (False when the caller stops it)."""
        if self.state != "running":
            return False
        self._restore_engine = restore
        self._cancel.set()
        return True

    def wait(self, timeout: Optional[float] = None) -> None:
        if self._thread:
            self._thread.join(timeout)

    def snapshot(self) -> Dict[str, Any]:
        eta = None
        if self.state == "running":
            left = max(self.total - self.done, 0)
            per = (
                (sum(self._per_run) / len(self._per_run))
                if self._per_run
                else (self._plan["load_seconds"] + BENCH_SECONDS)
            )
            eta = round(left * per + self._plan["load_seconds"])
        return {
            "state": self.state,
            "model": self.model,
            "long_context": self.long_context,
            "step": self.step,
            "label": self.label,
            "done": self.done,
            "total": self.total,
            "eta": eta,
            "started": self.started,
            "finished": self.finished,
            "baseline": self.baseline,
            "best": self.best,
            "flags": dict(self.flags),
            "noise": dict(self.noise),
            "trials": [dict(t) for t in self.trials],
            "error": self.error,
        }

    def _run(self, key: str, plan: Dict[str, Any]) -> None:
        model = catalog.model(key)
        facts = self.machine.facts()
        try:
            flags, best = self._search(model, facts, plan)
            self.flags, self.best = flags, best
            record = {
                "model": key,
                "active": True,
                "flags": flags,
                "before": self.baseline,
                "after": best,
                "noise": self.noise,
                "baselines": self.baselines,
                "trials": self.trials,
                "measured_at": int(time.time()),
                "bench": BENCH,
                "engine_version": self._version(),
                "machine": signature(facts),
                "long_context": self.long_context,
                "seconds": round(time.time() - (self.started or 0)),
            }
            self.profiles.save(key, record)
            self.step, self.label = "finish", ""
            self._ensure(key, None)  # run with the saved profile from now on
            self.state = "done"
        except Cancelled:
            self.state = "cancelled"
            self._restore(key)
        except (BenchError, EngineError) as e:
            self.state, self.error = "failed", str(e)
            self._restore(key)
        except Exception as e:  # a bug: say so, and leave the engine as it was
            self.state, self.error = "failed", f"{type(e).__name__}: {e}"
            self._restore(key)
        finally:
            self.finished = time.time()

    def _restore(self, key: str) -> None:
        """Back to how the engine ran before: the saved profile, or the launcher's defaults."""
        self._running_profile = None
        if not self._restore_engine:
            return
        try:
            self.engine.start(key)
        except EngineError:
            pass

    def _ensure(self, key: str, profile: Optional[Dict[str, Any]]) -> None:
        """Have the engine running with `profile` (None: the saved one), restarting only if it runs another."""
        model = catalog.model(key)
        want = self.profiles.flags(key, self.machine.facts()) if profile is None else clean_profile(model, profile)
        if self.engine.state == "running" and self.engine.model == key and self.engine.profile == want:
            self._running_profile = want
            return
        self.engine.start(key, profile)
        if not self.engine.wait_ready(cancel=self._cancel):
            if self._cancel.is_set():
                raise Cancelled()
            error = self.engine.error or {}
            raise EngineError("start", error.get("message") or "the engine did not start")
        self._running_profile = want

    def _trial(
        self,
        key: str,
        step: str,
        label: str,
        flags: Dict[str, Any],
        long_context: bool = False,
        warm: Optional[Callable[[str, str], None]] = None,
    ) -> Optional[Dict[str, float]]:
        """One configuration: start the engine with it (if it is not what runs now), warm up, measure."""
        if self._cancel.is_set():
            raise Cancelled()
        self.step, self.label = step, label
        t0 = time.time()
        trial = {"step": step, "label": label, "flags": dict(flags), "metrics": None, "adopted": False, "error": None}
        self.trials.append(trial)
        try:
            self._ensure(key, flags)
            base = self.engine.base_url()
            model_id = self._model_id(base, catalog.model(key)["model_id"])
            # One discarded request shaped like the measured ones (a fresh prompt as long as the prefill test, then
            # some generation): the first request after a start pays for things the later ones do not.
            ask(
                base,
                model_id,
                f"[warm-up {int(time.time() * 1000):x}] Read these notes, then describe them.\n\n"
                + filler(PREFILL_WORDS, seed=23),
                WARMUP_TOKENS,
            )
            if warm:
                warm(base, model_id)
            trial["metrics"] = measure(base, model_id, long_context, self._cancel)
        except (EngineError, BenchError) as e:
            if step == "baseline":
                raise
            trial["error"] = str(e)  # e.g. more threads than cores: this candidate is out, the run goes on
        finally:
            self.done += 1
            self._per_run.append(time.time() - t0)
        return trial["metrics"]

    def _model_id(self, base: str, default: str) -> str:
        try:
            with urllib.request.urlopen(base + "/models", timeout=10) as r:
                data = json.loads(r.read().decode("utf-8")).get("data") or []
            return str(data[0]["id"]) if data else default
        except Exception:
            return default

    def _auto_threads(self) -> Optional[int]:
        """The thread count the engine chose by itself, from its startup log; None when the log does not say."""
        for line in reversed(self.engine.log_tail(400)):
            match = re.search(r"routed experts: (\d+) CPU threads", line)
            if match:
                return int(match.group(1))
        return None

    def _warm_calibrate(self, base: str, model_id: str) -> None:
        """--miss-split calibrate fits its costs on the first 4,096 decode calls: generate until it says so."""
        for n in range(24):
            if self._cancel.is_set():
                raise Cancelled()
            if sum("miss split calibrate" in line for line in self.engine.log_tail(600)) >= 2:
                return
            ask(base, model_id, f"[warm {n}] {DECODE_PROMPTS[n % 2]}", 512)

    def _search(self, model: Dict[str, Any], facts: Dict[str, Any], plan: Dict[str, Any]):
        key = model["key"]
        settings = {s["id"]: s for s in catalog.LOSSLESS_SETTINGS}
        steps = [settings[s["id"]] for s in plan["steps"]]
        # A setting judged on a long context: both baselines carry the long-context numbers to compare with.
        long_context = any(s["metric"].startswith("long_") for s in steps)
        first = self._trial(key, "baseline", "", {}, long_context=long_context)
        if first is None:
            raise BenchError("the engine could not be measured")
        self.baseline = self.best = first
        self.baselines = [first]

        # Every candidate is the defaults plus one setting.
        for step in steps:
            budget = step["runs"]
            before = self.done
            if step["id"] == "threads":
                auto = self._auto_threads()
                cores = max(facts["cpu"]["physical_cores"], 1)
                for direction in (2, -2) if auto is not None else ():  # no count in the log: nothing to start from
                    previous, climbed = first, False
                    n = auto + direction
                    while 2 <= n <= cores and self.done - before < budget:
                        m = self._trial(key, step["id"], str(n), {step["key"]: n})
                        if m is None or gain(m, previous, step["metric"]) < STEP_GAIN:
                            break
                        previous, climbed = m, True
                        n += direction
                    if climbed:
                        break  # more threads helped: fewer is not worth an engine start
            elif step["id"] == "gpus":
                other = 1 if machine.gpus_for(model, facts) == 2 else 2
                self._trial(key, step["id"], str(other), {step["key"]: other})
            else:
                for value in step["tries"]:
                    self._trial(
                        key,
                        step["id"],
                        "on" if value is True else str(value),
                        {step["key"]: value},
                        long_context=step["metric"].startswith("long_"),
                        warm=self._warm_calibrate if value == "calibrate" else None,
                    )
            self.total -= budget - (self.done - before)  # runs this step did not need

        # The defaults again. The better of the two is what a setting has to beat; their distance is the noise.
        second = self._trial(key, "baseline_again", "", {}, long_context=long_context)
        if second is None:
            raise BenchError("the engine could not be measured a second time")
        reference, noise = reference_and_noise(first, second)
        self.baselines = [first, second]
        self.baseline = self.best = reference
        self.noise = noise

        # Per step, the best candidate on that step's number; kept only above GAIN and above the noise.
        kept = []
        for setting in catalog.LOSSLESS_SETTINGS:
            target = setting["metric"]
            tried = [t for t in self.trials if t["step"] == setting["id"] and t["metrics"]]
            if not tried:
                continue
            best = max(tried, key=lambda t: gain(t["metrics"], reference, target))
            if worth_it(best["metrics"], reference, target, noise):
                kept.append((gain(best["metrics"], reference, target), target, best))
        if len(kept) < 2 and plan["steps"]:
            self.total -= 1  # the plan counted a measurement of the kept settings together: not needed
        if not kept:
            return {}, reference
        strongest = max(kept, key=lambda k: k[0])[2]
        if len(kept) == 1:
            strongest["adopted"] = True
            return dict(strongest["flags"]), strongest["metrics"]
        # More than one: they were measured one at a time, so measure them together before trusting the sum.
        flags: Dict[str, Any] = {}
        for _, _, trial in kept:
            flags.update(trial["flags"])
        together = self._trial(key, "final", "", flags, long_context="kv_ram_active" in flags)
        holds = together is not None and any(worth_it(together, reference, target, noise) for _, target, _ in kept)
        if not holds:
            strongest["adopted"] = True  # together they do not hold up: the single best one, as it was measured
            return dict(strongest["flags"]), strongest["metrics"]
        for _, _, trial in kept:
            trial["adopted"] = True
        self.trials[-1]["adopted"] = True
        return flags, together
